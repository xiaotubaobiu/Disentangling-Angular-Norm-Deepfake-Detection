"""Frame -> video aggregation.

Strictly implements the spec's video aggregation protocol:

    P_video(V) = mean_t( softmax(frame_logits_t)[fake] )

i.e. softmax is applied PER FRAME, then the per-frame fake probabilities are
averaged. It is FORBIDDEN to average logits first and then softmax.

Video grouping key = (checkpoint_id, infer_mode, domain, method_id, video_id).
We include method_id in the key because in FF++/CDF the same pair_id (= the
'video_id' the loader emits) is reused across forgery methods (e.g. '000_003'
is generated by simswap, blendface, faceswap, ...). Without method_id in the
key, frames from different methods' videos that share a pair_id would be
averaged together — a silent semantic bug. Including method_id keeps each
(method, video) group separate, which is the correct reading of "average
per-frame prob_fake over the same video".

This file holds:
  - rows_to_frame_dataframe:   build a tidy per-frame DataFrame from collected
                               ModeScores + metadata.
  - aggregate_frames_to_videos: the strict video aggregation (spec section V).
"""
from __future__ import annotations

import numpy as np
import pandas as pd

# Group key for video aggregation. Real videos all share method_id='real' but
# their pair_ids are unique within 'real', so the key still groups correctly.
VIDEO_GROUP_KEYS = [
    "checkpoint_id",
    "backbone",
    "seed",
    "train_mode",
    "infer_mode",
    "domain",
    "method_id",
    "video_id",
]


def rows_to_frame_dataframe(
    *,
    frame_features,
    mode_scores_per_mode: dict,
    checkpoint_id: str,
    backbone: str,
    seed: int,
    train_mode: str,
    domain: str,
) -> pd.DataFrame:
    """Build the per-frame DataFrame for one (checkpoint, domain).

    Args:
        frame_features: FrameFeatures (aligned features/norms/labels/method_ids).
        mode_scores_per_mode: {mode_name: ModeScores} for the modes applicable
            to this checkpoint's train_mode.
        checkpoint_id, backbone, seed, train_mode, domain: row tag columns.

    Returns:
        DataFrame with one row per (frame, mode). The same frame appears once
        per infer_mode (so a rawtrain checkpoint yields 3 rows per frame, a
        normtrain checkpoint yields 1).
    """
    n = len(frame_features.video_ids)
    base = {
        "checkpoint_id": checkpoint_id,
        "backbone": backbone,
        "seed": seed,
        "train_mode": train_mode,
        "domain": domain,
        "video_id": frame_features.video_ids,
        "image_path": frame_features.image_paths,
        "label": frame_features.labels.tolist(),
        "method_id": frame_features.method_ids,
        "feature_norm": frame_features.feature_norms.tolist(),
    }

    # Tile base columns across modes. Scalar tag columns become [value]*n;
    # per-frame columns are repeated once per mode.
    modes = list(mode_scores_per_mode.keys())
    n_modes = len(modes)
    tiled: dict[str, list] = {}
    for key, values in base.items():
        if isinstance(values, (str, int)):
            tiled[key] = [values] * (n * n_modes)
        else:
            tiled[key] = list(values) * n_modes

    tiled["infer_mode"] = []
    tiled["real_logit"] = []
    tiled["fake_logit"] = []
    tiled["signed_logit"] = []
    tiled["prob_fake"] = []
    for mode in modes:
        s = mode_scores_per_mode[mode]
        tiled["infer_mode"].extend([mode] * n)
        tiled["real_logit"].extend(s.real_logit.tolist())
        tiled["fake_logit"].extend(s.fake_logit.tolist())
        tiled["signed_logit"].extend(s.signed_logit.tolist())
        tiled["prob_fake"].extend(s.prob_fake.tolist())

    df = pd.DataFrame(tiled)

    # prediction_correct = (prob_fake >= 0.5) == (label == 1).
    pred = (df["prob_fake"].to_numpy() >= 0.5).astype(np.int8)
    df["prediction_correct"] = (pred == df["label"].to_numpy()).astype(np.int8)

    # Stable column order (spec section IV).
    column_order = [
        "checkpoint_id", "backbone", "seed", "train_mode", "infer_mode",
        "domain", "method_id", "label", "video_id", "image_path",
        "feature_norm", "real_logit", "fake_logit", "signed_logit",
        "prob_fake", "prediction_correct",
    ]
    return df[column_order]


def aggregate_frames_to_videos(frame_df: pd.DataFrame) -> pd.DataFrame:
    """Strict spec aggregation: P_video = mean_t(softmax(frame_logits)[fake]).

    The per-frame prob_fake column already encodes softmax(logits)[:, 1]
    (computed in infer_modes). We group by VIDEO_GROUP_KEYS (which includes
    method_id so cross-method same-pair_id collisions don't mix frames) and
    take the mean of prob_fake — exactly the formula in the spec.

    This function does NOT re-softmax anything. The forbid-clause
    (no softmax-after-mean) is structurally guaranteed by the fact that we
    operate on prob_fake, not on averaged logits.

    Per spec section V, video-level columns:
      video_prob_fake  = mean(prob_fake)
      mean_feature_norm / std_feature_norm
      mean_signed_logit / std_signed_logit   # diagnostic only
      num_frames
    Plus the group key columns.
    """
    empty_cols = VIDEO_GROUP_KEYS + [
        "label", "video_prob_fake", "mean_feature_norm",
        "std_feature_norm", "mean_signed_logit", "std_signed_logit",
        "num_frames",
    ]
    if frame_df.empty:
        return pd.DataFrame(columns=empty_cols)

    grouped = frame_df.groupby(VIDEO_GROUP_KEYS, sort=False)

    video_df = grouped.agg(
        label=("label", "first"),
        video_prob_fake=("prob_fake", "mean"),
        mean_feature_norm=("feature_norm", "mean"),
        std_feature_norm=("feature_norm", "std"),
        mean_signed_logit=("signed_logit", "mean"),
        std_signed_logit=("signed_logit", "std"),
        num_frames=("prob_fake", "count"),
    ).reset_index()

    # std over a single frame is NaN; replace with 0 for downstream ease.
    video_df["std_feature_norm"] = video_df["std_feature_norm"].fillna(0.0)
    video_df["std_signed_logit"] = video_df["std_signed_logit"].fillna(0.0)

    return video_df
