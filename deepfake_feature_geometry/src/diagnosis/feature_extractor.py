"""Single-pass raw feature extraction.

For each (checkpoint, domain) we run the backbone once to get raw features h,
then derive all four inference modes from those raw features in CPU post-
processing (see infer_modes.py). This avoids re-running the backbone per mode.

The extraction mirrors scripts/evaluate_norm_correction.py: raw backbone
output, no autocast, fp32. The classifier's normalize_features flag is
intentionally NOT applied here — we apply (or skip) normalization in the
post-processing modes so each mode is a clean decomposition.

Backbone attribute: CLIPFineTuneBinaryClassifier exposes `.visual`, while
EfficientNetBinaryClassifier / DINOv2BinaryClassifier expose `.backbone`. We
prefer `.visual` if present (CLIP) and fall back to `.backbone`.

Important — frame metadata (method, video_id, frame_path, label) is taken
directly from `loader.dataset.records` rather than from the batch dict. This
is essential because in FF++/CDF the same pair_id (=video_id) is reused across
forgery methods (e.g. '000_003' is generated by simswap, blendface, faceswap,
...), so joining method by video_id alone would lose information. Reading
records frame-by-frame in the same order as iteration guarantees a correct
per-frame method label.
"""
from __future__ import annotations

from dataclasses import dataclass

import numpy as np
import torch

from diagnosis.method_map import method_to_id


@dataclass
class FrameFeatures:
    """Per-frame raw features and bookkeeping.

    All arrays/lists are aligned by index.
    """

    features: np.ndarray           # (N, D) float32, raw backbone output
    feature_norms: np.ndarray      # (N,) float32, ||feature||
    video_ids: list[str]           # (N,)
    image_paths: list[str]         # (N,)
    labels: np.ndarray             # (N,) int64
    method_ids: list[str]          # (N,) normalized method_id (e.g. 'simswap', 'real', 'dfd_native')


@torch.no_grad()
def extract_raw_features(model: torch.nn.Module, loader, device: str | torch.device) -> FrameFeatures:
    """Run the backbone once over a loader and collect raw features + metadata.

    Args:
        model: a built model. CLIPFineTuneBinaryClassifier exposes `.visual`;
               EfficientNetBinaryClassifier / DINOv2BinaryClassifier expose
               `.backbone`. Either attribute yields raw pooled features.
        loader: a DataLoader yielding batches with key 'image'. The loader's
                .dataset must expose .records (FrameClassificationDataset does)
                so we can read per-frame method/label/video_id in order.
        device: cuda or cpu.

    The records are consumed in dataset order (i.e. the loader must NOT
    shuffle). build_eval_loader is called with distributed=False and shuffle
    is disabled for eval loaders, so this holds.
    """
    raw_model = model.module if hasattr(model, "module") else model
    if hasattr(raw_model, "visual"):
        visual = raw_model.visual
    elif hasattr(raw_model, "backbone"):
        visual = raw_model.backbone
    else:
        raise AttributeError(
            f"Model {type(raw_model).__name__} exposes neither .visual nor .backbone; "
            "cannot extract raw features."
        )

    # Pull per-frame metadata from the underlying records (same order as the
    # loader iterates when shuffle=False and distributed=False).
    records = getattr(loader.dataset, "records", None)
    if records is None:
        raise AttributeError(
            "loader.dataset has no .records attribute; cannot extract per-frame method labels."
        )
    method_ids = [method_to_id(getattr(r, "method", "real")) for r in records]
    video_ids = [getattr(r, "pair_id", getattr(r, "video_id", "")) for r in records]
    image_paths = [r.frame_path for r in records]
    labels = np.array([int(r.label) for r in records], dtype=np.int64)

    feats_chunks: list[np.ndarray] = []
    for batch in loader:
        images = batch["image"].to(device, non_blocking=True).float()
        features = visual(images).float().cpu().numpy()
        feats_chunks.append(features)

    features = np.concatenate(feats_chunks, axis=0)
    feature_norms = np.linalg.norm(features, axis=-1).astype(np.float32)

    n_records = len(records)
    n_features = features.shape[0]
    if n_features != n_records:
        raise RuntimeError(
            f"Mismatch between records ({n_records}) and extracted features "
            f"({n_features}). Loader may have shuffled or dropped data — "
            "verify build_eval_loader was called with distributed=False."
        )

    return FrameFeatures(
        features=features,
        feature_norms=feature_norms,
        video_ids=video_ids,
        image_paths=image_paths,
        labels=labels,
        method_ids=method_ids,
    )
